/** Career start. Anything ending in PRESENT is shown as ongoing. */
export const PRESENT = 2026;
export const years = { from: 2022, to: PRESENT };
export const careerSpan = `${years.from}–present`;

/** "2024", "2023–24", or "2025–present". */
export const yearSpan = (s: number, e: number) =>
  e >= PRESENT ? `${s}–present` : s === e ? String(s) : `${s}–${String(e).slice(2)}`;
